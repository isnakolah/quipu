package main

// `quipu guide` prints the agent handbook. `--sync` regenerates every copy
// agents read in this repository: the Quipu block in AGENTS.md, the
// @AGENTS.md import in CLAUDE.md, the short rule in .agent/rules, and in the
// Quipu source repository the plugin skills. TestGuidesInSync fails when a
// committed copy drifts from the handbook or from the CLI's rule tables.

import (
	"errors"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/isnakolah/quipu/internal/guide"
)

const (
	guideBegin = "<!-- quipu:guide:begin (generated by `quipu guide --sync`; do not edit) -->"
	guideEnd   = "<!-- quipu:guide:end -->"
)

const skillFrontmatter = `---
name: quipu
description: Work in a Quipu repository. Take GitHub Issues with quipu start, open PRs that say Refs #N, finish with quipu done, and follow the guard. Use whenever the repository has .github/quipu/config.yaml or the user mentions Quipu.
---

`

const agentRule = "# Quipu\n\nThis repository runs on Quipu. Before any change, read AGENTS.md (or run `quipu guide`): take work with `quipu start --next --json`, open PRs whose body says `Refs #N`, finish with `quipu done N --json`, and follow each result's `next`. Everything off that flow is blocked.\n"

// renderGuide is the handbook with the CLI's own rule tables filled in.
func renderGuide() string {
	var rules strings.Builder
	rules.WriteString("| Code | Why | Do instead |\n|---|---|---|\n")
	for _, rule := range guardRules {
		fmt.Fprintf(&rules, "| `%s` | %s | %s |\n", rule.Code, cell(rule.Why), cell(rule.Instead))
	}
	var failures strings.Builder
	failures.WriteString("| Code | What happened | Next |\n|---|---|---|\n")
	for _, kind := range flowErrors {
		fmt.Fprintf(&failures, "| `%s` | %s | %s |\n", kind.Code, cell(kind.When), cell(kind.Next))
	}
	text := strings.Replace(guide.Agent, "{{guard-rules}}\n", rules.String(), 1)
	return strings.Replace(text, "{{flow-errors}}\n", failures.String(), 1)
}

func cell(text string) string { return strings.ReplaceAll(text, "|", `\|`) }

// guideFiles returns every generated copy for the repository at top, given
// the current contents read through read.
func guideFiles(top string, read func(string) (string, bool)) map[string]string {
	handbook := renderGuide()
	files := map[string]string{".agent/rules/quipu.md": agentRule}
	agents, _ := read("AGENTS.md")
	files["AGENTS.md"] = withGuideBlock(agents, handbook)
	claude, ok := read("CLAUDE.md")
	switch {
	case !ok:
		files["CLAUDE.md"] = "# Claude Code\n\nThis repository's agent instructions live in AGENTS.md.\n\n@AGENTS.md\n"
	case !strings.Contains(claude, "@AGENTS.md"):
		files["CLAUDE.md"] = strings.TrimRight(claude, "\n") + "\n\n@AGENTS.md\n"
	default:
		files["CLAUDE.md"] = claude
	}
	for _, provider := range []string{"claude", "codex"} {
		skill := filepath.Join("plugins", provider, "quipu", "skills", "quipu", "SKILL.md")
		if _, err := os.Stat(filepath.Join(top, filepath.Dir(skill))); err == nil {
			files[skill] = skillFrontmatter + handbook
		}
	}
	return files
}

// withGuideBlock replaces the generated block in an AGENTS.md, or appends it,
// keeping whatever the repository wrote around it.
func withGuideBlock(existing, handbook string) string {
	block := guideBegin + "\n" + handbook + guideEnd + "\n"
	start, end := strings.Index(existing, guideBegin), strings.Index(existing, guideEnd)
	if start >= 0 && end > start {
		return existing[:start] + block + strings.TrimPrefix(existing[end+len(guideEnd):], "\n")
	}
	if strings.TrimSpace(existing) == "" {
		return block
	}
	return strings.TrimRight(existing, "\n") + "\n\n" + block
}

func readUnder(top string) func(string) (string, bool) {
	return func(path string) (string, bool) {
		raw, err := os.ReadFile(filepath.Join(top, path))
		return string(raw), err == nil
	}
}

// syncGuides writes the generated copies under top and returns those changed.
func syncGuides(top string, write bool) ([]string, error) {
	read := readUnder(top)
	var changed []string
	for path, body := range guideFiles(top, read) {
		if current, _ := read(path); current == body {
			continue
		}
		changed = append(changed, path)
		if !write {
			continue
		}
		target := filepath.Join(top, path)
		if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
			return changed, err
		}
		if err := os.WriteFile(target, []byte(body), 0o644); err != nil {
			return changed, err
		}
	}
	return changed, nil
}

func guideCommand(args []string) error {
	fs := flag.NewFlagSet("guide", flag.ContinueOnError)
	sync := fs.Bool("sync", false, "regenerate AGENTS.md, CLAUDE.md, and the other agent instruction copies")
	check := fs.Bool("check", false, "exit non-zero when a generated copy is out of date")
	if err := fs.Parse(args); err != nil {
		return err
	}
	if !*sync && !*check {
		fmt.Print(renderGuide())
		return nil
	}
	here, err := currentWorktree()
	if err != nil {
		return err
	}
	changed, err := syncGuides(here.Top, *sync)
	if err != nil {
		return err
	}
	for _, path := range changed {
		fmt.Println(path)
	}
	if *check && !*sync && len(changed) > 0 {
		return errors.New("agent guides are out of date; the owner runs `quipu guide --sync`")
	}
	return nil
}
